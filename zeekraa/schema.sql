CREATE TABLE IF NOT EXISTS admins (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  email VARCHAR(190) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS invitations (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  slug VARCHAR(80) NOT NULL UNIQUE,
  template VARCHAR(30) NOT NULL DEFAULT 'royal',
  lang CHAR(2) NOT NULL DEFAULT 'ar',
  cover_preset VARCHAR(30) NULL,
  intro_title VARCHAR(160) NULL,
  intro_text VARCHAR(255) NULL,
  photo_caption VARCHAR(255) NULL,
  caption_pos VARCHAR(8) NULL,
  groom VARCHAR(120) NOT NULL,
  bride VARCHAR(120) NOT NULL,
  message TEXT NULL,
  music_url VARCHAR(500) NULL,
  music_file VARCHAR(255) NULL,
  cover_image VARCHAR(255) NULL,
  gallery TEXT NULL,
  access_password VARCHAR(255) NULL,
  accent_color CHAR(7) NULL,
  owner_email VARCHAR(190) NULL UNIQUE,
  owner_password VARCHAR(255) NULL,
  is_active TINYINT(1) NOT NULL DEFAULT 1,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS events (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  invitation_id INT UNSIGNED NOT NULL,
  title VARCHAR(120) NOT NULL,
  event_at DATETIME NOT NULL,
  venue VARCHAR(190) NULL,
  address VARCHAR(255) NULL,
  map_url VARCHAR(500) NULL,
  sort_order INT NOT NULL DEFAULT 0,
  FOREIGN KEY (invitation_id) REFERENCES invitations(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS guests (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  invitation_id INT UNSIGNED NOT NULL,
  name VARCHAR(120) NOT NULL,
  phone VARCHAR(30) NULL,
  max_guests TINYINT UNSIGNED NOT NULL DEFAULT 1,
  token CHAR(16) NOT NULL UNIQUE,
  FOREIGN KEY (invitation_id) REFERENCES invitations(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS rsvps (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  invitation_id INT UNSIGNED NOT NULL,
  guest_id INT UNSIGNED NULL,
  name VARCHAR(120) NOT NULL,
  phone VARCHAR(30) NULL,
  attending TINYINT(1) NOT NULL,
  party_size TINYINT UNSIGNED NOT NULL DEFAULT 1,
  note VARCHAR(500) NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (invitation_id) REFERENCES invitations(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
